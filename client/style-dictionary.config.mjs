// Style Dictionary pipeline — the ONE transform (ADR-028 decisão 2). DTCG (client/tokens/*.json)
// is the single source of truth; this emits the web outputs (CSS vars + a typed TS object). Native
// outputs (Fase 3) are an ADDITION here, never a touch of the source. The tool is replaceable; what
// this protects is the source format, not the transform.
//
// Why a build script and not a static config: the two authored themes (light/dark) define the SAME
// semantic names with different values, so they cannot share one Style Dictionary `source` (they
// would collide on `color.bg`). We run one instance per theme, then concatenate into a single
// tokens.css (`:root` for light + `[data-theme="dark"]` override). Determinism (no timestamp header)
// is mandatory: outputs are committed and must not churn on rebuild (PLANO §0.4).
//
// Run: `npm run tokens` (after editing client/tokens/). Outputs land in src/ui/tokens/ and are
// committed — there is NO runtime generation.
import StyleDictionary from 'style-dictionary'
import { readFile, writeFile, rm } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { buildDesignSystem, dsProjectAvailable } from './scripts/ds-tokens.mjs'
import { buildDsIcons } from './scripts/ds-icons.mjs'

const root = dirname(fileURLToPath(import.meta.url))
const SRC = join(root, 'tokens')
const OUT = join(root, 'src', 'ui', 'tokens')
const TMP = join(root, '.sd-tmp')

// Primitive color ramps stay PRIVATE: they are resolved into the semantic values at build time and
// never become public CSS vars (ADR-028 decisão 3 — only the semantic tier is the public API).
const RAMPS = new Set(['greige', 'petrol', 'indigo'])
const isPrimitiveColor = (t) => t.path[0] === 'color' && RAMPS.has(t.path[1])

// Text styles (`font.style.*`, typography.json) are composites of aliases to the public font
// tokens: they feed the Design System's type.groups (scripts/ds-tokens.mjs) and are NOT public CSS
// vars — the client reads the four underlying tokens, never a composite.
const isTextStyle = (t) => t.path[0] === 'font' && t.path[1] === 'style'
const isPublic = (t) => !isPrimitiveColor(t) && !isTextStyle(t)

// Themed tokens (differ per mode): the color semantics + the overlay shadow. These are the only
// things the dark theme re-emits, under [data-theme="dark"].
const isThemed = (t) => (t.path[0] === 'color' && !isPrimitiveColor(t)) || t.path[0] === 'shadow'

const GEN_HEADER = `/**
 * GENERATED by Style Dictionary — DO NOT EDIT BY HAND.
 * Source of truth: client/tokens/*.json (W3C DTCG). Regenerate with \`npm run tokens\`.
 * ADR-028: the DTCG source is canonical; this file is a generated output. Editing here edits
 * the wrong place — change the token JSON and rebuild.
 */`

// Minimal transform: name only. Values pass through verbatim (px / ms / hex / cubic-bezier exactly
// as authored in §0.2) — no rem/seconds/color mutation, so the emitted CSS matches the frozen spec.
const TRANSFORMS = ['name/kebab']

// Typed TS output: a nested object of var() REFERENCES (not raw values). This is the theme-safe
// design — a raw-value map would freeze the light theme into JS and never switch with [data-theme].
// JS-driven styling reads e.g. tokens.color.accent === 'var(--color-accent)'.
StyleDictionary.registerFormat({
  name: 'tayet/ts',
  format: ({ dictionary }) => {
    const tree = {}
    const tokens = dictionary.allTokens
      .filter(isPublic)
      .sort((a, b) => a.path.join('.').localeCompare(b.path.join('.')))
    for (const t of tokens) {
      let node = tree
      for (let i = 0; i < t.path.length - 1; i++) {
        const k = t.path[i]
        if (typeof node[k] !== 'object' || node[k] === null) node[k] = {}
        node = node[k]
      }
      node[t.path[t.path.length - 1]] = `var(--${t.name})`
    }
    return `${GEN_HEADER}\n\nexport const tokens = ${JSON.stringify(tree, null, 2)} as const\n\nexport type Tokens = typeof tokens\n`
  },
})

// One CSS build target (one theme), written to TMP and later concatenated.
function cssTarget({ themeFile, destination, selector, filter }) {
  return new StyleDictionary({
    source: [join(SRC, 'primitives.json'), join(SRC, themeFile), join(SRC, 'density.json'), join(SRC, 'typography.json')],
    platforms: {
      css: {
        transforms: TRANSFORMS,
        buildPath: `${TMP}/`,
        files: [
          {
            destination,
            format: 'css/variables',
            filter,
            // No timestamp header (determinism) and no var-references (primitives are private, so
            // every reference must resolve to its literal value).
            options: { selector, showFileHeader: false, outputReferences: false },
          },
        ],
      },
    },
  })
}

await rm(TMP, { recursive: true, force: true })

// Light = base: everything EXCEPT the private primitive ramps and the text-style composites (semantics + space/radius/font/
// motion/density/shadow), under :root (default theme — ADR-028 decisão 4 / PLANO §0.4).
const lightSd = cssTarget({
  themeFile: 'theme.light.json',
  destination: 'light.css',
  selector: ':root',
  filter: isPublic,
})

// Dark = override: only the themed tokens, under [data-theme="dark"]. density.json is included in
// source for parity but filtered out of the output (densidade is non-themed — emitted once in :root).
const darkSd = cssTarget({
  themeFile: 'theme.dark.json',
  destination: 'dark.css',
  selector: '[data-theme="dark"]',
  filter: isThemed,
})

const tsSd = new StyleDictionary({
  source: [join(SRC, 'primitives.json'), join(SRC, 'theme.light.json'), join(SRC, 'density.json'), join(SRC, 'typography.json')],
  platforms: {
    ts: {
      transforms: TRANSFORMS,
      buildPath: `${OUT}/`,
      files: [{ destination: 'tokens.ts', format: 'tayet/ts', filter: isPublic }],
    },
  },
})

await lightSd.buildAllPlatforms()
await darkSd.buildAllPlatforms()
await tsSd.buildAllPlatforms()

const light = (await readFile(join(TMP, 'light.css'), 'utf8')).trim()
const dark = (await readFile(join(TMP, 'dark.css'), 'utf8')).trim()
await writeFile(join(OUT, 'tokens.css'), `${GEN_HEADER}\n\n${light}\n\n${dark}\n`)

await rm(TMP, { recursive: true, force: true })

// Design System target `tayet/ds-tokens` (ADR-070 dec. 1): an ADDITION — same DTCG source, a third
// output under design/system/project/ for the Claude Design System Artifact type. Skipped when the
// tree has no design/ (the public source): the client outputs never depend on it.
if (dsProjectAvailable()) {
  await buildDesignSystem()
  await buildDsIcons()
  console.log('tokens: wrote src/ui/tokens/tokens.css + tokens.ts + design/system/project/')
} else {
  console.log('tokens: design/ absent — Design System target skipped')
  console.log('tokens: wrote src/ui/tokens/tokens.css + tokens.ts')
}
