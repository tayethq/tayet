import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { renderEmojiTable, TABLE_PATH } from '../../scripts/gen-emoji.mjs'
import { EMOJI_ALIASES, EMOJI_SOURCE, EMOJI_TABLE } from '../../src/api/slack/emoji-table'
import { emojiOf, isEmojiChar, nameOf } from '../../src/api/slack/emoji'

// The emoji table (ADR-087 dec. 6; PLANO-AGENTES §0.3.12): generated from the iamcal set, committed,
// and the rules of code around it (skin tones, aliases, the reverse lookup).

describe('emoji table — generated, no drift', () => {
  it('regenerating it in memory gives the committed file, byte for byte', () => {
    expect(renderEmojiTable()).toBe(readFileSync(TABLE_PATH, 'utf8'))
  })

  it('names the source version and is sorted by name', () => {
    expect(EMOJI_SOURCE).toMatch(/^emojibase-data@\d+\.\d+\.\d+$/)
    // The file's own order (Object.keys would put integer-like names such as `100` first).
    const names = [...readFileSync(TABLE_PATH, 'utf8').matchAll(/^ {2}("[^"]+"): /gm)].map((m) => JSON.parse(m[1] as string) as string)
    expect(names.length).toBe(Object.keys(EMOJI_TABLE).length)
    expect(names.length).toBeGreaterThan(1500)
    expect([...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))).toEqual(names)
    expect(readFileSync(TABLE_PATH, 'utf8')).toMatch(/^\/\/ GENERATED by scripts\/gen-emoji\.mjs — DO NOT EDIT/)
  })
})

describe('name → character', () => {
  it('Slack names, aliases and colons', () => {
    expect(emojiOf('thumbsup')).toBe('👍')
    expect(emojiOf('+1')).toBe('👍')
    expect(emojiOf(':tada:')).toBe('🎉')
    expect(emojiOf('heart')).toBe('❤️')
    expect(emojiOf('white_check_mark')).toBe('✅')
  })

  it('name::skin-tone-N (2–6) = base + modifier (the base’s U+FE0F dropped)', () => {
    expect(emojiOf('thumbsup::skin-tone-2')).toBe('👍\u{1F3FB}')
    expect(emojiOf('+1::skin-tone-6')).toBe('👍\u{1F3FF}')
    expect(emojiOf('point_up::skin-tone-3')).toBe('☝\u{1F3FC}')
    expect(emojiOf('thumbsup::skin-tone-1')).toBeUndefined()
    expect(emojiOf('thumbsup::skin-tone-7')).toBeUndefined()
    expect(emojiOf('nope::skin-tone-2')).toBeUndefined()
  })

  it('unknown names, and the prototype is not a table', () => {
    expect(emojiOf('not_an_emoji_name')).toBeUndefined()
    expect(emojiOf('constructor')).toBeUndefined()
    expect(emojiOf('__proto__')).toBeUndefined()
  })
})

describe('character → name (a reaction read back)', () => {
  it('the first name of the character in the preset; U+FE0F ignored', () => {
    expect(nameOf('👍')).toBe('+1')
    expect(EMOJI_ALIASES.has('thumbsup')).toBe(true)
    expect(nameOf('❤️')).toBe('heart')
    expect(nameOf('❤')).toBe('heart')
    expect(nameOf('🎉')).toBe('tada')
  })

  it('base + modifier → base::skin-tone-N; the round trip holds', () => {
    expect(nameOf('👍\u{1F3FD}')).toBe('+1::skin-tone-4')
    for (const n of ['+1::skin-tone-2', 'wave::skin-tone-5', 'point_up::skin-tone-3']) expect(nameOf(emojiOf(n) as string)).toBe(n)
  })

  it('a character with no name stays the character', () => {
    expect(nameOf('👩🏽‍💻')).toBe('👩🏽‍💻')
    expect(nameOf('x')).toBe('x')
  })

  it('every primary name round-trips through the table', () => {
    for (const [name, char] of Object.entries(EMOJI_TABLE)) {
      if (!EMOJI_ALIASES.has(name)) expect(nameOf(char)).toBe(name)
    }
  })
})

describe('a character as a name', () => {
  it('one emoji grapheme only', () => {
    for (const c of ['👍', '❤️', '👍🏽', '🇧🇷', '1️⃣', '👩🏽‍💻']) expect(isEmojiChar(c)).toBe(true)
    for (const c of ['', 'a', 'thumbsup', '👍👍', ':+1:', '👍 ', '1']) expect(isEmojiChar(c)).toBe(false)
  })
})
