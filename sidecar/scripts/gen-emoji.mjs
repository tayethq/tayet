// Generates src/api/slack/emoji-table.ts (ADR-087 dec. 6; PLANO-AGENTES §0.3.12): Slack's emoji names
// (the iamcal set, as emojibase-data publishes it in `en/shortcodes/iamcal.json`) → the character.
//
//   node scripts/gen-emoji.mjs          writes the table (committed)
//
// - The iamcal preset is keyed by emojibase hexcode, which drops the variation selector (U+FE0F); the
//   character is the fully-qualified `emoji` of `en/data.json` (skins included) when it has the hexcode,
//   otherwise the code points of the hexcode itself.
// - The table is sorted by name. `EMOJI_ALIASES` lists every name that is not the first of its
//   character in the preset: the reverse lookup (character → name) skips them, so 👍 reads `+1`, as Slack.
// - The skin-tone names (`skin-tone-2` … `skin-tone-6`) are in the preset; `name::skin-tone-N` is a rule
//   of code (slack/emoji.ts), not rows here.
// The unit `slack-emoji.test.ts` regenerates the text in memory and fails on any drift from the file.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
export const TABLE_PATH = join(here, '..', 'src', 'api', 'slack', 'emoji-table.ts')

const fromHex = (hexcode) => String.fromCodePoint(...hexcode.split('-').map((h) => parseInt(h, 16)))

export function renderEmojiTable() {
  const pkg = JSON.parse(readFileSync(require.resolve('emojibase-data/package.json'), 'utf8'))
  const iamcal = require('emojibase-data/en/shortcodes/iamcal.json')
  const data = require('emojibase-data/en/data.json')
  const byHex = new Map()
  for (const e of data) {
    byHex.set(e.hexcode, e.emoji)
    for (const s of e.skins ?? []) byHex.set(s.hexcode, s.emoji)
  }
  const rows = new Map()
  const aliases = new Set()
  for (const [hexcode, value] of Object.entries(iamcal)) {
    const names = Array.isArray(value) ? value : [value]
    const char = byHex.get(hexcode) ?? fromHex(hexcode)
    names.forEach((name, i) => {
      if (rows.has(name)) throw new Error(`duplicate emoji name: ${name}`)
      rows.set(name, char)
      if (i > 0) aliases.add(name)
    })
  }
  const names = [...rows.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
  const q = (s) => JSON.stringify(s)
  const lines = [
    '// GENERATED by scripts/gen-emoji.mjs — DO NOT EDIT (the unit slack-emoji.test.ts fails on drift).',
    `// Source: emojibase-data@${pkg.version} en/shortcodes/iamcal.json (characters from en/data.json).`,
    '// Slack emoji name → character, sorted by name.',
    `export const EMOJI_SOURCE = ${q(`emojibase-data@${pkg.version}`)}`,
    '',
    'export const EMOJI_TABLE: Readonly<Record<string, string>> = {',
    ...names.map((n) => `  ${q(n)}: ${q(rows.get(n))},`),
    '}',
    '',
    '// Names that are not the first of their character (the reverse lookup skips them).',
    'export const EMOJI_ALIASES: ReadonlySet<string> = new Set([',
    ...[...aliases].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)).map((n) => `  ${q(n)},`),
    '])',
    '',
  ]
  return lines.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(TABLE_PATH, renderEmojiTable())
  console.log(`wrote ${TABLE_PATH}`)
}
